import { Octokit } from '@octokit/rest';
import { CommitPlanEntry, ExecutionProgress } from '@/types';

export interface ExecutionConfig {
  token: string;
  owner: string;
  repo: string;
  branch: string;
  authorName: string;
  authorEmail: string;
  message?: string;
}

// Generates a randomized time between 08:00 and 22:00 for a date
function randomizeTime(date: Date): Date {
  const result = new Date(date);
  result.setHours(Math.floor(Math.random() * 14) + 8);
  result.setMinutes(Math.floor(Math.random() * 60));
  result.setSeconds(Math.floor(Math.random() * 60));
  return result;
}

// Creates an updated blob for contributions.md
async function createUpdatedBlob(
  octokit: Octokit,
  owner: string,
  repo: string,
  existingContent: string,
  newLine: string
): Promise<string> {
  const updatedContent = existingContent + newLine;
  const encoded = Buffer.from(updatedContent).toString('base64');
  const { data } = await octokit.git.createBlob({
    owner,
    repo,
    content: encoded,
    encoding: 'base64',
  });
  return data.sha;
}

export async function executeCommitPlan(
  plan: CommitPlanEntry[],
  config: ExecutionConfig,
  onProgress?: (progress: ExecutionProgress) => void
): Promise<void> {
  const octokit = new Octokit({ auth: config.token });
  const {
    owner,
    repo,
    branch,
    authorName,
    authorEmail,
    message = 'chore: update',
  } = config;

  const totalCommits = plan.reduce((sum, p) => sum + p.count, 0);
  let completed = 0;
  let commitContent = '# Contributions\n\nGenerated by commit-bot-web\n\n';

  // 1. Resolve branch HEAD SHA
  let currentSha: string;
  try {
    const headRef = await octokit.git.getRef({
      owner,
      repo,
      ref: `heads/${branch}`,
    });
    currentSha = headRef.data.object.sha;
  } catch {
    // If repo has no branch (empty repo), create initial commit
    const initialBlob = await octokit.git.createBlob({
      owner,
      repo,
      content: Buffer.from('# Contributions\n').toString('base64'),
      encoding: 'base64',
    });

    const initialTree = await octokit.git.createTree({
      owner,
      repo,
      tree: [
        {
          path: 'README.md',
          mode: '100644',
          type: 'blob',
          sha: initialBlob.data.sha,
        },
      ],
    });

    const initialCommit = await octokit.git.createCommit({
      owner,
      repo,
      message: 'Initial commit',
      tree: initialTree.data.sha,
      parents: [],
    });

    await octokit.git.createRef({
      owner,
      repo,
      ref: `refs/heads/${branch}`,
      sha: initialCommit.data.sha,
    });

    currentSha = initialCommit.data.sha;
  }

  // 2. Get current commit's tree SHA
  const headCommit = await octokit.git.getCommit({
    owner,
    repo,
    commit_sha: currentSha,
  });
  let currentTreeSha = headCommit.data.tree.sha;

  // 3. Sort plan by date ascending
  const sortedPlan = [...plan].sort((a, b) => a.date.getTime() - b.date.getTime());

  // 4. Sequential commit creation loop
  for (const entry of sortedPlan) {
    for (let i = 0; i < entry.count; i++) {
      const commitDate = randomizeTime(entry.date);
      const isoDate = commitDate.toISOString();
      const dateLabel = `${isoDate.split('T')[0]} ${commitDate.toTimeString().slice(0, 8)}`;
      const newLine = `${dateLabel} | commit #${completed + 1}\n`;

      // Create updated blob
      const blobSha = await createUpdatedBlob(
        octokit,
        owner,
        repo,
        commitContent,
        newLine
      );
      commitContent += newLine;

      // Create new tree pointing to new blob
      const { data: treeData } = await octokit.git.createTree({
        owner,
        repo,
        base_tree: currentTreeSha,
        tree: [
          {
            path: 'contributions.md',
            mode: '100644',
            type: 'blob',
            sha: blobSha,
          },
        ],
      });
      currentTreeSha = treeData.sha;

      // Create backdated commit
      const { data: commitData } = await octokit.git.createCommit({
        owner,
        repo,
        message,
        tree: currentTreeSha,
        parents: [currentSha],
        author: {
          name: authorName,
          email: authorEmail,
          date: isoDate,
        },
        committer: {
          name: authorName,
          email: authorEmail,
          date: isoDate,
        },
      });

      currentSha = commitData.sha;
      completed++;

      onProgress?.({
        completed,
        total: totalCommits,
        currentDate: entry.date.toISOString().split('T')[0],
        sha: currentSha,
      });

      // Checkpoint every 50 commits to persist progress on large batches
      if (completed % 50 === 0) {
        await octokit.git.updateRef({
          owner,
          repo,
          ref: `heads/${branch}`,
          sha: currentSha,
          force: true,
        });
      }
    }
  }

  // 5. Final ref update to point branch to the last created commit
  await octokit.git.updateRef({
    owner,
    repo,
    ref: `heads/${branch}`,
    sha: currentSha,
    force: true,
  });
}
