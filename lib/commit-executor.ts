import { Octokit } from '@octokit/rest';
import { CommitPlanEntry, ExecutionProgress } from '@/types';
import { CONTRIBUTION_FILE, DEFAULT_MESSAGE } from '@/lib/core/constants';

export interface ExecutionConfig {
  token: string;
  owner: string;
  repo: string;
  branch: string;
  authorName: string;
  authorEmail: string;
  message?: string;
}

const HEADER = '# Contributions\n\nGenerated by commit-bot-web\n\n';

// Random time between 08:00 and 21:59 UTC on the given UTC calendar date ("YYYY-MM-DD")
function randomTimeOnDate(date: string): Date {
  const result = new Date(`${date}T00:00:00Z`);
  result.setUTCHours(8 + Math.floor(Math.random() * 14));
  result.setUTCMinutes(Math.floor(Math.random() * 60));
  result.setUTCSeconds(Math.floor(Math.random() * 60));
  return result;
}

async function readExistingContributions(
  octokit: Octokit,
  owner: string,
  repo: string,
  ref: string
): Promise<string> {
  try {
    const { data } = await octokit.repos.getContent({ owner, repo, path: CONTRIBUTION_FILE, ref });
    if (!Array.isArray(data) && data.type === 'file' && 'content' in data) {
      return Buffer.from(data.content, 'base64').toString('utf8');
    }
  } catch (err: unknown) {
    if ((err as { status?: number }).status !== 404) throw err;
  }
  return HEADER;
}

export async function executeCommitPlan(
  plan: CommitPlanEntry[],
  config: ExecutionConfig,
  onProgress?: (progress: ExecutionProgress) => void,
  signal?: AbortSignal
): Promise<void> {
  const octokit = new Octokit({ auth: config.token });
  const { owner, repo, branch, authorName, authorEmail, message = DEFAULT_MESSAGE } = config;

  const totalCommits = plan.reduce((sum, p) => sum + p.count, 0);
  let completed = 0;

  // 1. Resolve branch HEAD. The branch must already exist (repositories are created with an initial commit).
  const headRef = await octokit.git.getRef({ owner, repo, ref: `heads/${branch}` });
  const originalSha = headRef.data.object.sha;
  let currentSha = originalSha;

  const headCommit = await octokit.git.getCommit({ owner, repo, commit_sha: currentSha });
  let currentTreeSha = headCommit.data.tree.sha;

  let commitContent = await readExistingContributions(octokit, owner, repo, currentSha);

  // Fast-forward only: fails if the branch moved while we were building commits.
  const advanceRef = async () => {
    if (currentSha === originalSha) return;
    await octokit.git.updateRef({ owner, repo, ref: `heads/${branch}`, sha: currentSha, force: false });
  };

  const sortedPlan = [...plan].sort((a, b) => a.date.localeCompare(b.date));
  let lastPushedSha = originalSha;

  try {
    for (const entry of sortedPlan) {
      for (let i = 0; i < entry.count; i++) {
        if (signal?.aborted) {
          throw new Error('Execution cancelled');
        }

        const isoDate = randomTimeOnDate(entry.date).toISOString();
        commitContent += `${isoDate} | commit #${completed + 1}\n`;

        const { data: blob } = await octokit.git.createBlob({
          owner,
          repo,
          content: Buffer.from(commitContent).toString('base64'),
          encoding: 'base64',
        });

        const { data: tree } = await octokit.git.createTree({
          owner,
          repo,
          base_tree: currentTreeSha,
          tree: [{ path: CONTRIBUTION_FILE, mode: '100644', type: 'blob', sha: blob.sha }],
        });
        currentTreeSha = tree.sha;

        const identity = { name: authorName, email: authorEmail, date: isoDate };
        const { data: commit } = await octokit.git.createCommit({
          owner,
          repo,
          message,
          tree: currentTreeSha,
          parents: [currentSha],
          author: identity,
          committer: identity,
        });

        currentSha = commit.sha;
        completed++;

        onProgress?.({ completed, total: totalCommits, currentDate: entry.date, sha: currentSha });

        // Checkpoint every 50 commits so a dropped connection keeps its progress
        if (completed % 50 === 0) {
          await advanceRef();
          lastPushedSha = currentSha;
        }
      }
    }
  } finally {
    // Keep whatever was built, including after a cancel or an API error part way through
    if (currentSha !== lastPushedSha) {
      await advanceRef();
    }
  }
}
